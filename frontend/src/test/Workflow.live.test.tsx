import { expect, it, vi } from "vitest";
import { act, render, screen, fireEvent, waitFor, cleanup } from "@testing-library/react";
import { App } from "../App";
import { getAuthSession } from "../services/api";

it.skipIf(import.meta.env.VITE_RUN_ISOLATED_WORKFLOW !== "1")("isolated live UI: stable identities, claim/chat/transfer/explicit close and personal reports", async () => {
  const nativeFetch = globalThis.fetch;
  const base = "http://127.0.0.1:18000/api/v1";
  const health = await nativeFetch(`${base}/health`).then(r => r.json());
  expect(health.environment).toBe("verification");
  const call = async (path: string, token?: string, method = "GET", body?: unknown) => {
    const response = await nativeFetch(`${base}${path}`, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), "Content-Type": "application/json" }, ...(body ? { body: JSON.stringify(body) } : {}) });
    if (!response.ok) throw new Error(`${path}: ${response.status} ${await response.text()}`);
    return response.json();
  };
  const loginAPI = (email: string) => call("/auth/login", undefined, "POST", { email, password: "Isolated-Test-Password123!" });
  const admin = await call("/auth/login", undefined, "POST", { email: "admin@ticketdesk.enterprise", password: "Admin@12345" });
  const teams = await call("/users/support-teams", admin.access_token);
  const categories = await call("/tickets/categories", admin.access_token);
  const tag = Date.now();
  const people: Record<string, { id: number; email: string }> = {};
  for (const [key, role, team] of [["employee", "employee", null], ["software", "agent", teams[0].id], ["cloud", "agent", teams[1].id]] as const) {
    people[key] = await call("/users", admin.access_token, "POST", { full_name: `Isolated ${key}`, email: `${key}.${tag}@example.com`, role, password: "Isolated-Test-Password123!", support_team_id: team });
  }
  vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} });
  vi.stubGlobal("fetch", (input: string | URL | Request, options?: RequestInit) => {
    const url = String(input);
    const resolved = url.startsWith("/api/v1") ? `http://127.0.0.1:18000${url}` : url;
    if (!resolved.startsWith("http://127.0.0.1:18000/")) throw new Error("Refusing to contact the user's application during verification");
    return nativeFetch(resolved, options);
  });
  const loginUI = async (email: string, destination: string, password = "Isolated-Test-Password123!") => {
    fireEvent.change(await screen.findByLabelText("Corporate Email"), { target: { value: email } });
    fireEvent.change(screen.getByLabelText("Password"), { target: { value: password } });
    fireEvent.click(screen.getByRole("button", { name: "Sign In to TicketDesk" }));
    await waitFor(() => expect(window.location.pathname).toBe(destination));
  };
  const visit = async (path: string) => { await act(async () => { window.history.pushState({}, "", path); window.dispatchEvent(new PopStateEvent("popstate")); }); };
  sessionStorage.clear(); localStorage.clear(); window.history.replaceState({}, "", "/login");
  try {
    render(<App />);
    await loginUI("admin@ticketdesk.enterprise", "/dashboard", "Admin@12345");
    await screen.findByText("Enterprise Service Operations Center", {}, { timeout: 10000 });
    const adminSession = getAuthSession()!;
    fireEvent.click(screen.getByRole("link", { name: "Settings" }));
    await screen.findByText("Platform Settings & Cloud Readiness");
    expect(getAuthSession()?.id).toBe(adminSession.id);
    expect((await call("/auth/me", getAuthSession()!.accessToken)).id).toBe(admin.user.id);
    fireEvent.click(screen.getByTitle("Logout"));
    // The employee cannot return to the administrator's Settings route.
    await loginUI(people.employee.email, "/dashboard");
    await screen.findByText("My Total Tickets");
    const employeeSession = getAuthSession()!;
    fireEvent.click(screen.getByRole("link", { name: "Create Support Ticket" }));
    await screen.findByText("Submit New IT Support Ticket");
    const subject = `Isolated end-to-end request ${tag}`;
    fireEvent.change(document.querySelector('input[name="subject"]')!, { target: { value: subject } });
    const category = document.querySelector('select[name="category_id"]')!;
    const team = document.querySelector('select[name="support_team_id"]')!;
    await waitFor(() => expect(category.querySelectorAll("option").length).toBeGreaterThan(1));
    await waitFor(() => expect(team.querySelectorAll("option").length).toBeGreaterThan(1));
    fireEvent.change(category, { target: { value: String(categories[0].id) } });
    fireEvent.change(team, { target: { value: String(teams[0].id) } });
    fireEvent.change(document.querySelector('textarea[name="description"]')!, { target: { value: "An isolated employee issue requiring software then cloud diagnosis." } });
    fireEvent.click(screen.getByRole("button", { name: "Submit Support Ticket" }));
    await waitFor(() => expect(window.location.pathname).toMatch(/\/tickets\/TKT-/));
    await screen.findByText(subject);
    expect(getAuthSession()?.id).toBe(employeeSession.id);
    expect((await call("/auth/me", getAuthSession()!.accessToken)).id).toBe(people.employee.id);
    const original = (await call("/tickets", employeeSession.accessToken)).items.find((row: { subject: string }) => row.subject === subject);
    fireEvent.click(screen.getByTitle("Logout"));
    const originalPath = `/tickets/${original.ticket_number}`;
    await loginUI(people.software.email, originalPath);
    await screen.findByText(subject);
    const softwareSession = getAuthSession()!;
    expect(screen.queryByRole("link", { name: /SLA Alerts/ })).not.toBeInTheDocument();
    fireEvent.click(await screen.findByRole("button", { name: "Accept Ticket" }));
    fireEvent.click(await screen.findByRole("button", { name: "Start Progress" }));
    await screen.findByRole("button", { name: "Mark Pending" });
    fireEvent.change(screen.getByPlaceholderText("Write a reply or status update..."), { target: { value: "Software investigation completed; cloud specialty needed." } });
    fireEvent.click(screen.getByRole("button", { name: "Post Public Comment" }));
    await screen.findByText("Software investigation completed; cloud specialty needed.");
    fireEvent.click(screen.getByRole("button", { name: "Transfer Ticket" }));
    fireEvent.change(screen.getByLabelText("Transfer target team"), { target: { value: String(teams[1].id) } });
    fireEvent.change(screen.getByLabelText("Transfer target consultant"), { target: { value: String(people.cloud.id) } });
    fireEvent.change(screen.getByLabelText("Transfer reason and completed work"), { target: { value: "Software work done; investigate cloud connectivity" } });
    fireEvent.click(screen.getByRole("button", { name: "Confirm Transfer" }));
    await screen.findByText("Linked request history");
    const old = await call(`/tickets/${original.id}`, employeeSession.accessToken);
    expect(old.status).toBe("closed");
    const successor = old.lineage.find((row: { relation: string }) => row.relation === "successor");
    fireEvent.click(screen.getByTitle("Logout"));
    await loginUI(people.cloud.email, originalPath);
    await screen.findByText(subject);
    const cloudSession = getAuthSession()!;
    // The saved route is the original ticket. Open the successor for the handoff.
    await visit(`/tickets/${successor.ticket_number}`);
    const prior = await screen.findByRole("link", { name: new RegExp(`previous: ${original.ticket_number}`) });
    fireEvent.click(prior);
    await screen.findByText("Software investigation completed; cloud specialty needed.");
    expect(screen.queryByRole("button", { name: "Close Ticket" })).not.toBeInTheDocument();
    await visit(`/tickets/${successor.ticket_number}`);
    fireEvent.click(await screen.findByRole("button", { name: "Accept Ticket" }));
    fireEvent.click(await screen.findByRole("button", { name: "Start Progress" }));
    await screen.findByRole("button", { name: "Mark Pending" });
    await call(`/tickets/${successor.id}/comments`, employeeSession.accessToken, "POST", { body: "The issue is solved; we agree to close it." });
    expect((await call(`/tickets/${successor.id}`, cloudSession.accessToken)).status).toBe("in_progress");
    expect(getAuthSession()?.id).toBe(cloudSession.id);
    const closeTicket = screen.getByRole("button", { name: "Close Ticket" });
    await waitFor(() => expect(closeTicket).toBeEnabled());
    fireEvent.click(closeTicket);
    await waitFor(async () => expect((await call(`/tickets/${successor.id}`, cloudSession.accessToken)).status).toBe("closed"));
    const personal = await call("/reports/tickets?scope=all&user_id=1", softwareSession.accessToken);
    expect(personal.records.map((row: { id: number }) => row.id)).toEqual([original.id]);
    fireEvent.click(screen.getByRole("link", { name: "Reports & Analytics" }));
    await screen.findByText("My Work Reports & Analytics");
    expect(getAuthSession()?.id).toBe(cloudSession.id);
    const freshEmployee = await loginAPI(people.employee.email);
    const freshSoftware = await loginAPI(people.software.email);
    const escalated: { id: number; ticket_number: string }[] = [];
    for (let index = 0; index < 2; index++) {
      const pending = await call("/tickets", freshEmployee.access_token, "POST", { subject: `Admin escalation ${tag} ${index}`, description: "Pending administrator review from consultant", category_id: categories[0].id, support_team_id: teams[0].id });
      await call(`/tickets/${pending.id}/accept`, freshSoftware.access_token, "POST");
      escalated.push(await call(`/tickets/${pending.id}/transfer`, freshSoftware.access_token, "POST", { escalate_to_admin: true, assigned_agent_id: admin.user.id, reason: "Administrator review and routing required" }));
    }
    fireEvent.click(screen.getByTitle("Logout"));
    await loginUI("admin@ticketdesk.enterprise", "/reports", "Admin@12345");
    await screen.findByRole("heading", { name: "Enterprise Reports & SLA Analytics" });
    fireEvent.click(screen.getByRole("link", { name: "Assigned to Me" }));
    await screen.findByText(escalated[0].ticket_number);
    expect(screen.getAllByText(new RegExp(`From Isolated software`)).length).toBeGreaterThan(0);
    await visit(`/tickets/${escalated[0].ticket_number}`);
    fireEvent.click(await screen.findByRole("button", { name: "Accept Ticket" }));
    await screen.findByRole("button", { name: "Start Progress" });
    fireEvent.click(screen.getByRole("link", { name: "My Tickets" }));
    await screen.findByText(escalated[0].ticket_number);
    await visit(`/tickets/${escalated[1].ticket_number}`);
    fireEvent.click(await screen.findByRole("button", { name: "Reject / Redirect" }));
    fireEvent.change(screen.getByLabelText("Transfer target team"), { target: { value: String(teams[1].id) } });
    fireEvent.change(screen.getByLabelText("Transfer reason and completed work"), { target: { value: "Administrator redirects to cloud specialists" } });
    fireEvent.click(screen.getByRole("button", { name: "Confirm Transfer" }));
    await screen.findByText("Linked request history");
    await waitFor(async () => expect((await call(`/tickets/${escalated[1].id}`, getAuthSession()!.accessToken)).status).toBe("closed"));
    const redirected = await call(`/tickets/${escalated[1].id}`, getAuthSession()!.accessToken);
    expect(redirected.status).toBe("closed");
    expect(redirected.sla.sla_health).toBe("closed");
    const inbox = await call("/tickets?assigned_to_me=true", getAuthSession()!.accessToken);
    expect(inbox.items.some((row: { id: number }) => row.id === escalated[1].id)).toBe(false);
    expect(freshEmployee.user.id).toBe(people.employee.id);
    expect(getAuthSession()?.subject).toBe(String(admin.user.id));
  } finally {
    cleanup(); sessionStorage.clear(); localStorage.clear(); vi.unstubAllGlobals();
  }
}, 40000);
